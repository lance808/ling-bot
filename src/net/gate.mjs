/**
 * 联网总闸 —— **唯一判定实现**
 *
 * ## 这个文件存在的理由
 *
 * 「联网关了」是一句安全相关的断言。如果判定散落在三处（插件入口、宿主工厂、
 * 界面快照），迟早会出现一处判 true、一处判 false。症状极难排查：
 * 界面显示"已关闭"，而插件其实还在发请求；或者反过来，模型说搜不到，
 * 而界面显示"已开启"。
 *
 * 所以：**只有这里能回答"现在能不能联网"**，其余模块一律调用它。
 *
 * ## 这个开关控制的是什么（必须说清楚）
 *
 * 它控制 **Ling-bot 进程自己发起的外网访问**：搜索 API、网页正文抓取。
 * 它**不**控制、也不可能控制：
 *
 *   · 模型服务商在自己服务端做的检索（那是上游行为，我们看不见也拦不住）；
 *   · QQ 网关自己的网络；
 *   · 用户装的其他软件。
 *
 * 界面上必须原样写清这一点。否则用户关掉开关后看到模型"好像还能查到东西"
 * （其实是模型自己的知识或上游检索），会以为开关是假的，进而不再相信它。
 *
 * ## 为什么缺省是「开」
 *
 * 这是**既有行为的延续**：本轮之前 Ling-bot 没有任何出站搜索能力，所以
 * "配置里没有 network 字段"的旧部署，行为必须完全不变。同时 `web-search`
 * 插件默认**不**在 `plugins.enabled` 里 —— 铺盘 ≠ 启用，所以默认配置下
 * 一个搜索工具都不存在。"缺省开"不会凭空打开联网。
 */

/**
 * 从配置对象里取总闸状态。
 *
 * 只认真正的布尔 `true` / `false`：字符串 `"false"`、数字 `0` 之类
 * 一律按缺省处理，**不做真值转换**。理由：这类脏值的来源通常是手改配置，
 * 而"把 'false' 当成 true"意味着用户写了关闭却没关掉 —— 这是安全方向上
 * 唯一不能容忍的错法。
 *
 * @param {unknown} config 解析后的配置（可以是任何脏数据）
 * @returns {boolean}
 */
export function networkEnabledFrom(config) {
  const flag = /** @type {any} */ (config)?.network?.enabled;
  if (typeof flag === 'boolean') return flag;
  return true;
}

/**
 * 联网关闭时给模型/调用方的统一结果。
 *
 * 三句话缺一不可：
 *   1. 现在为什么不行（开关关着）；
 *   2. 不许做什么（重试、换工具绕）；
 *   3. 该怎么做（如实说明）。
 *
 * @param {string} [what] 被拒绝的能力名（便于排查）
 * @returns {{ok: false, code: 'E4080', message: string}}
 */
export function networkDisabledResult(what = '联网') {
  return {
    ok: false,
    code: 'E4080',
    message:
      `联网已关闭（管理员在《插件设置 → 联网搜索》里关掉了总开关），${what}被拒绝，没有发出任何请求。`
      + '不要重试，也不要换个工具绕过；请基于已有知识回答，并如实说明你无法联网核实。',
  };
}

